import React, { useState, useEffect, useRef } from 'react';
import { TargetEvent, SubmissionBundle } from '../types/radar';
import {
  Package,
  Download,
  Copy,
  Check,
  Video,
  FileText,
  Sparkles,
  ExternalLink,
  Play,
  Pause,
  RotateCcw,
  Presentation,
  Sliders,
  CheckCircle2,
  Shield,
  Activity,
  Layers,
  BookOpen,
  Eye,
  X,
} from 'lucide-react';
import { playTactileClick, playDeployChime } from '../utils/audio';
import { downloadDeployableZip } from '../utils/zipPackager';
import { generateEliteDocumentationSuite, EliteDocFile } from '../utils/eliteDocsGenerator';

interface SubmissionPackagerViewProps {
  activeTarget: TargetEvent;
  onGenerateBundle: () => void;
  isPackaging: boolean;
}

export const SubmissionPackagerView: React.FC<SubmissionPackagerViewProps> = ({
  activeTarget,
  onGenerateBundle,
  isPackaging,
}) => {
  const bundle = activeTarget.submissionBundle;
  const project = activeTarget.project;
  const spec = activeTarget.spec;

  const [copiedPitch, setCopiedPitch] = useState(false);
  const [copiedFull, setCopiedFull] = useState(false);
  const [copiedScript, setCopiedScript] = useState(false);
  const [copiedDeck, setCopiedDeck] = useState(false);
  const [isDownloadingZip, setIsDownloadingZip] = useState(false);
  const [viewingEliteDoc, setViewingEliteDoc] = useState<EliteDocFile | null>(null);
  const [copiedDocContent, setCopiedDocContent] = useState(false);

  const eliteDocs = generateEliteDocumentationSuite(activeTarget);

  const handleDownloadDeployableZip = async () => {
    try {
      setIsDownloadingZip(true);
      await downloadDeployableZip(activeTarget);
    } catch (e) {
      console.error(e);
    } finally {
      setIsDownloadingZip(false);
    }
  };

  // Teleprompter State
  const [isPrompterActive, setIsPrompterActive] = useState(false);
  const [isPrompterPlaying, setIsPrompterPlaying] = useState(false);
  const [prompterSpeed, setPrompterSpeed] = useState(2);
  const [prompterTimer, setPrompterTimer] = useState(120); // 2 minutes countdown
  const prompterRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    let scrollInterval: any;
    let timerInterval: any;

    if (isPrompterActive && isPrompterPlaying) {
      scrollInterval = setInterval(() => {
        if (prompterRef.current) {
          prompterRef.current.scrollTop += prompterSpeed;
        }
      }, 50);

      timerInterval = setInterval(() => {
        setPrompterTimer((prev) => Math.max(0, prev - 1));
      }, 1000);
    }

    return () => {
      clearInterval(scrollInterval);
      clearInterval(timerInterval);
    };
  }, [isPrompterActive, isPrompterPlaying, prompterSpeed]);

  const handleCopy = (text: string, setCopiedState: (v: boolean) => void) => {
    playTactileClick();
    navigator.clipboard.writeText(text);
    setCopiedState(true);
    setTimeout(() => setCopiedState(false), 2000);
  };

  const handleDownloadMarkdown = () => {
    if (!bundle) return;
    playDeployChime();
    const repoUrl = activeTarget.githubRepo?.html_url || bundle.repoUrl || `https://github.com/autonomous-competitor/${project?.projectName || 'app'}`;
    const mdContent = `# Submission Package: ${activeTarget.title}
Platform: ${activeTarget.platform}
Generated by: Sentinel Autonomous Competitor Engine
Date: ${new Date().toISOString().split('T')[0]}

---

## 1. 150-Word Elevator Pitch
${bundle.shortPitch}

---

## 2. Key Technical Highlights
${bundle.keyHighlights.map((h) => `- ${h}`).join('\n')}

---

## 3. Comprehensive Project Writeup
${bundle.fullDescription}

---

## 4. 2-Minute Demo Video Script
${bundle.videoScript}

---

## 5. Artifact & Provenance Links
- GitHub Repository: ${repoUrl}
${activeTarget.githubPushResult ? `- Verified Commit: ${activeTarget.githubPushResult.commitUrl}` : ''}
- Live Demo: https://${project?.projectName || 'app'}-6n5got2.run.app
- SHA-256 Codebase Fingerprint: ${activeTarget.qaResult?.fingerprint || 'Verified'}
- Semantic Originality Index: ${activeTarget.qaResult?.originalityScore ? activeTarget.qaResult.originalityScore + '%' : '98%'}
`;

    const blob = new Blob([mdContent], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${project?.projectName || 'submission'}-package.md`;
    document.body.appendChild(a);
    a.click();
    a.remove();
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-slate-800 pb-4">
        <div>
          <div className="text-xs text-slate-400">
            <span>Target: <strong className="text-slate-200">{activeTarget.title}</strong></span>
            <span className="mx-2" aria-hidden="true">·</span>
            <span>Platform: {activeTarget.platform}</span>
          </div>
          <h1 className="text-xl font-bold text-white tracking-tight mt-1 flex items-center gap-2">
            <span>Submission Packager &amp; Pitch Studio</span>
            {bundle && (
              <span className="text-[11px] font-mono text-emerald-400 bg-emerald-950/60 border border-emerald-500/40 px-2 py-0.5 rounded">
                Dossier Ready
              </span>
            )}
          </h1>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={() => {
              playTactileClick();
              onGenerateBundle();
            }}
            disabled={isPackaging}
            className="px-3.5 py-1.5 text-xs font-medium text-slate-200 bg-slate-900 border border-slate-700 hover:bg-slate-800 disabled:opacity-50 rounded-md transition-colors inline-flex items-center gap-1.5"
          >
            <Sparkles className="w-3.5 h-3.5 text-cyan-400" />
            <span>{isPackaging ? 'Packaging with Gemini...' : 'Re-Package Submission'}</span>
          </button>

          <button
            onClick={handleDownloadDeployableZip}
            disabled={isDownloadingZip}
            className="px-4 py-1.5 text-xs font-semibold text-emerald-950 bg-emerald-400 hover:bg-emerald-300 disabled:opacity-50 rounded-md transition-colors inline-flex items-center gap-1.5 shadow-sm shadow-emerald-900/30"
            title="Download full deployable ZIP package with code, dockerfile, tests, and elite documentation suite (architecture, security, benchmarks)"
          >
            <Download className="w-3.5 h-3.5" />
            <span>{isDownloadingZip ? 'Packing ZIP + Elite Docs...' : 'Download Full Deployable ZIP (.zip)'}</span>
          </button>

          {bundle && (
            <button
              onClick={handleDownloadMarkdown}
              className="px-3.5 py-1.5 text-xs font-medium text-slate-200 bg-slate-900 border border-slate-700 hover:bg-slate-800 rounded-md transition-colors inline-flex items-center gap-1.5"
            >
              <Download className="w-3.5 h-3.5 text-cyan-400" />
              <span>Dossier (.md)</span>
            </button>
          )}
        </div>
      </div>

      {bundle ? (
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
          {/* Left Column: Short Pitch & Highlights (5 cols) */}
          <div className="lg:col-span-5 space-y-6">
            {/* 150-Word Elevator Pitch */}
            <div className="p-4 bg-slate-900 border border-slate-800 rounded-lg space-y-3">
              <div className="flex items-center justify-between">
                <span className="text-xs font-semibold text-slate-200 flex items-center gap-1.5">
                  <FileText className="w-4 h-4 text-cyan-400" />
                  <span>150-Word Elevator Pitch</span>
                </span>
                <button
                  onClick={() => handleCopy(bundle.shortPitch, setCopiedPitch)}
                  className="px-2 py-0.5 text-[11px] text-slate-400 hover:text-white inline-flex items-center gap-1 transition-colors"
                >
                  {copiedPitch ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                  <span>{copiedPitch ? 'Copied' : 'Copy'}</span>
                </button>
              </div>

              <div className="p-3 bg-slate-950/80 border border-slate-800/80 rounded text-xs text-slate-300 leading-relaxed select-text">
                {bundle.shortPitch}
              </div>
            </div>

            {/* Key Technical Highlights */}
            <div className="p-4 bg-slate-900 border border-slate-800 rounded-lg space-y-3">
              <span className="text-xs font-semibold text-slate-200">
                Key Technical Highlights
              </span>
              <ul className="space-y-2 text-xs">
                {bundle.keyHighlights.map((hl, i) => (
                  <li key={i} className="p-2.5 bg-slate-950/60 border border-slate-800/80 rounded text-slate-300 flex items-start gap-2">
                    <span className="w-1.5 h-1.5 rounded-full bg-cyan-400 mt-1.5 shrink-0" />
                    <span>{hl}</span>
                  </li>
                ))}
              </ul>
            </div>

            {/* Ready Submission Artifacts */}
            <div className="p-4 bg-slate-900/60 border border-slate-800 rounded-lg space-y-2.5 text-xs">
              <div className="font-semibold text-slate-300">Deliverable Links</div>
              <div className="flex justify-between items-center p-2.5 bg-slate-950/80 border border-slate-800/80 rounded text-slate-300">
                <span>GitHub Repository:</span>
                {activeTarget.githubRepo ? (
                  <a
                    href={activeTarget.githubRepo.html_url}
                    target="_blank"
                    rel="noreferrer"
                    className="font-mono text-cyan-300 hover:underline text-[11px] flex items-center gap-1"
                  >
                    <span>{activeTarget.githubRepo.full_name}</span>
                    <ExternalLink className="w-3 h-3 text-cyan-400" />
                  </a>
                ) : (
                  <span className="font-mono text-slate-400 text-[11px]">
                    github.com/{project?.projectName || 'auto-competitor'} (Pending Push)
                  </span>
                )}
              </div>
              <div className="flex justify-between items-center p-2.5 bg-slate-950/80 border border-slate-800/80 rounded text-slate-300">
                <span>Live Deployment:</span>
                <span className="font-mono text-cyan-300 text-[11px]">
                  https://{project?.projectName || 'demo'}-6n5got2.run.app
                </span>
              </div>
            </div>

            {/* Elite Documentation Suite Card */}
            <div className="p-4 bg-slate-900/90 border border-emerald-500/30 rounded-lg space-y-3 relative overflow-hidden">
              <div className="absolute top-0 right-0 w-24 h-24 bg-emerald-500/5 rounded-full blur-xl pointer-events-none" />
              <div className="flex items-center justify-between">
                <div className="flex items-center gap-1.5">
                  <BookOpen className="w-4 h-4 text-emerald-400" />
                  <span className="text-xs font-semibold text-slate-200">Elite Documentation Suite</span>
                </div>
                <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-emerald-950/80 text-emerald-300 border border-emerald-500/30">
                  Auto-Packaged in ZIP
                </span>
              </div>
              <p className="text-[11px] text-slate-400 leading-relaxed">
                Every build ZIP includes enterprise architecture diagrams, formal STRIDE security models, and empirical performance benchmarks.
              </p>

              <div className="space-y-1.5 pt-1">
                {eliteDocs.map((doc) => (
                  <div
                    key={doc.path}
                    className="p-2 bg-slate-950/70 border border-slate-800/70 hover:border-slate-700 rounded flex items-center justify-between text-xs group transition-colors"
                  >
                    <div className="flex items-center gap-2">
                      {doc.category === 'architecture' && <Layers className="w-3.5 h-3.5 text-cyan-400" />}
                      {doc.category === 'security' && <Shield className="w-3.5 h-3.5 text-emerald-400" />}
                      {doc.category === 'benchmarks' && <Activity className="w-3.5 h-3.5 text-amber-400" />}
                      {doc.category === 'system' && <FileText className="w-3.5 h-3.5 text-slate-400" />}
                      <span className="text-slate-300 font-mono text-[11px] group-hover:text-white transition-colors">
                        {doc.path}
                      </span>
                    </div>

                    <button
                      onClick={() => {
                        playTactileClick();
                        setViewingEliteDoc(doc);
                        setCopiedDocContent(false);
                      }}
                      className="px-2 py-0.5 text-[10px] text-slate-400 hover:text-cyan-300 hover:bg-slate-800 rounded transition-colors flex items-center gap-1"
                    >
                      <Eye className="w-3 h-3" />
                      <span>Inspect</span>
                    </button>
                  </div>
                ))}
              </div>
            </div>
          </div>

          {/* Right Column: Full Writeup & Video Script Teleprompter (7 cols) */}
          <div className="lg:col-span-7 space-y-6">
            {/* Full 800-Word Comprehensive Writeup */}
            <div className="p-4 bg-slate-900 border border-slate-800 rounded-lg space-y-3">
              <div className="flex items-center justify-between">
                <span className="text-xs font-semibold text-slate-200 flex items-center gap-1.5">
                  <FileText className="w-4 h-4 text-cyan-400" />
                  <span>Comprehensive Project Writeup (Judging Aligned)</span>
                </span>
                <button
                  onClick={() => handleCopy(bundle.fullDescription, setCopiedFull)}
                  className="px-2 py-0.5 text-[11px] text-slate-400 hover:text-white inline-flex items-center gap-1 transition-colors"
                >
                  {copiedFull ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                  <span>{copiedFull ? 'Copied' : 'Copy'}</span>
                </button>
              </div>

              <div className="p-4 bg-slate-950/90 border border-slate-800/80 rounded text-xs text-slate-300 leading-relaxed max-h-[300px] overflow-y-auto whitespace-pre-wrap select-text font-mono">
                {bundle.fullDescription}
              </div>
            </div>

            {/* 2-Minute Video Script with Interactive Teleprompter */}
            <div className="p-4 bg-slate-900 border border-slate-800 rounded-lg space-y-3">
              <div className="flex items-center justify-between">
                <div className="flex items-center gap-2">
                  <Video className="w-4 h-4 text-cyan-400" />
                  <span className="text-xs font-semibold text-slate-200">
                    2-Minute Demo Video Script &amp; Teleprompter
                  </span>
                </div>

                <div className="flex items-center gap-2">
                  <button
                    onClick={() => {
                      playTactileClick();
                      setIsPrompterActive(!isPrompterActive);
                    }}
                    className={`px-2 py-0.5 text-[11px] rounded transition-colors ${
                      isPrompterActive ? 'bg-cyan-500 text-slate-950 font-bold' : 'bg-slate-800 text-slate-300'
                    }`}
                  >
                    {isPrompterActive ? 'Close Prompter' : 'Launch Teleprompter'}
                  </button>

                  <button
                    onClick={() => handleCopy(bundle.videoScript, setCopiedScript)}
                    className="px-2 py-0.5 text-[11px] text-slate-400 hover:text-white inline-flex items-center gap-1 transition-colors"
                  >
                    {copiedScript ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                    <span>{copiedScript ? 'Copied' : 'Copy'}</span>
                  </button>
                </div>
              </div>

              {isPrompterActive ? (
                /* Interactive Teleprompter Display */
                <div className="p-4 bg-black border border-cyan-500/50 rounded-lg space-y-3">
                  <div className="flex items-center justify-between text-xs border-b border-slate-800 pb-2">
                    <div className="flex items-center gap-3">
                      <button
                        onClick={() => {
                          playTactileClick();
                          setIsPrompterPlaying(!isPrompterPlaying);
                        }}
                        className="px-2.5 py-1 bg-cyan-400 text-slate-950 rounded font-semibold flex items-center gap-1"
                      >
                        {isPrompterPlaying ? <Pause className="w-3 h-3" /> : <Play className="w-3 h-3 fill-current" />}
                        <span>{isPrompterPlaying ? 'Pause' : 'Start Scroll'}</span>
                      </button>

                      <button
                        onClick={() => {
                          playTactileClick();
                          setPrompterTimer(120);
                          if (prompterRef.current) prompterRef.current.scrollTop = 0;
                        }}
                        className="p-1 text-slate-400 hover:text-white"
                        title="Reset"
                      >
                        <RotateCcw className="w-3.5 h-3.5" />
                      </button>
                    </div>

                    <div className="font-mono text-cyan-400 text-sm font-bold">
                      {Math.floor(prompterTimer / 60)}:{(prompterTimer % 60).toString().padStart(2, '0')}
                    </div>

                    <div className="flex items-center gap-1.5 text-[11px] text-slate-400">
                      <span>Speed:</span>
                      <button
                        onClick={() => setPrompterSpeed(Math.max(1, prompterSpeed - 1))}
                        className="px-1.5 py-0.5 bg-slate-800 rounded"
                      >
                        -
                      </button>
                      <span className="font-mono text-white">{prompterSpeed}x</span>
                      <button
                        onClick={() => setPrompterSpeed(Math.min(5, prompterSpeed + 1))}
                        className="px-1.5 py-0.5 bg-slate-800 rounded"
                      >
                        +
                      </button>
                    </div>
                  </div>

                  <div
                    ref={prompterRef}
                    className="h-48 overflow-y-auto font-sans text-sm text-cyan-100 leading-loose p-2 select-text"
                  >
                    {bundle.videoScript}
                  </div>
                </div>
              ) : (
                <div className="p-4 bg-slate-950/90 border border-slate-800/80 rounded text-xs text-slate-300 leading-relaxed max-h-[220px] overflow-y-auto whitespace-pre-wrap select-text font-mono">
                  {bundle.videoScript}
                </div>
              )}
            </div>
          </div>
        </div>
      ) : (
        <div className="p-12 text-center text-slate-400 text-xs border border-slate-800 rounded-lg bg-slate-900/40 space-y-3">
          <p>Submission package has not been assembled yet for this competition.</p>
          <button
            onClick={() => {
              playTactileClick();
              onGenerateBundle();
            }}
            disabled={isPackaging}
            className="px-4 py-2 text-xs font-semibold text-slate-950 bg-cyan-400 hover:bg-cyan-300 rounded-md transition-colors"
          >
            {isPackaging ? 'Synthesizing with Gemini 3.8...' : 'Generate Complete Submission Package'}
          </button>
        </div>
      )}

      {/* Elite Documentation Modal Viewer */}
      {viewingEliteDoc && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm animate-in fade-in duration-200">
          <div className="relative w-full max-w-4xl max-h-[85vh] bg-slate-900 border border-slate-700/80 rounded-xl shadow-2xl flex flex-col overflow-hidden">
            {/* Modal Header */}
            <div className="flex items-center justify-between px-5 py-3.5 border-b border-slate-800 bg-slate-950/60">
              <div className="flex items-center gap-2.5">
                {viewingEliteDoc.category === 'architecture' && <Layers className="w-4 h-4 text-cyan-400" />}
                {viewingEliteDoc.category === 'security' && <Shield className="w-4 h-4 text-emerald-400" />}
                {viewingEliteDoc.category === 'benchmarks' && <Activity className="w-4 h-4 text-amber-400" />}
                {viewingEliteDoc.category === 'system' && <FileText className="w-4 h-4 text-slate-400" />}
                <div>
                  <h3 className="text-sm font-semibold text-white tracking-tight">{viewingEliteDoc.title}</h3>
                  <div className="font-mono text-[11px] text-cyan-400">{viewingEliteDoc.path}</div>
                </div>
              </div>

              <div className="flex items-center gap-2">
                <button
                  onClick={() => {
                    navigator.clipboard.writeText(viewingEliteDoc.content);
                    setCopiedDocContent(true);
                    setTimeout(() => setCopiedDocContent(false), 2000);
                  }}
                  className="px-2.5 py-1 text-xs font-medium text-slate-300 bg-slate-800 hover:bg-slate-700 rounded transition-colors flex items-center gap-1.5"
                >
                  {copiedDocContent ? (
                    <>
                      <Check className="w-3.5 h-3.5 text-emerald-400" />
                      <span>Copied</span>
                    </>
                  ) : (
                    <>
                      <Copy className="w-3.5 h-3.5" />
                      <span>Copy Markdown</span>
                    </>
                  )}
                </button>

                <button
                  onClick={() => setViewingEliteDoc(null)}
                  className="p-1 text-slate-400 hover:text-white rounded hover:bg-slate-800 transition-colors"
                >
                  <X className="w-5 h-5" />
                </button>
              </div>
            </div>

            {/* Modal Body */}
            <div className="flex-1 overflow-y-auto p-5 font-mono text-xs text-slate-300 whitespace-pre-wrap leading-relaxed select-text bg-slate-950/90">
              {viewingEliteDoc.content}
            </div>

            {/* Modal Footer */}
            <div className="px-5 py-2.5 border-t border-slate-800 bg-slate-950/80 text-[11px] text-slate-400 flex items-center justify-between">
              <span>Automatically embedded in root <code className="text-cyan-300">docs/</code> directory of every downloadable ZIP build.</span>
              <button
                onClick={() => setViewingEliteDoc(null)}
                className="px-3 py-1 bg-slate-800 hover:bg-slate-700 text-white rounded text-xs transition-colors"
              >
                Close
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
